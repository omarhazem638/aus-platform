function detail(opts) {
  const { idx, emoji, name, en, accent, desc, how, features } = opts;
  const s = pres.addSlide();
  chrome(s, accent, C.gold);

  // header
  s.addShape(pres.shapes.RECTANGLE, { x:11.7,y:0.32,w:1.1,h:0.85, fill:{color:C.navyMid}, line:{color:accent,width:1.2} });
  s.addText(emoji, { x:11.7,y:0.34,w:1.1,h:0.82, fontSize:34, align:'center' });
  s.addText(name, { x:3.2,y:0.32,w:8.3,h:0.55, fontSize:27, color:C.white, bold:true, fontFace:FH, align:'right' });
  s.addText(en, { x:3.2,y:0.92,w:8.3,h:0.35, fontSize:13, color:accent, fontFace:FB, align:'right', italic:true });
  // number badge
  s.addText('أداة ' + idx, { x:0.55,y:0.5,w:1.6,h:0.5, fontSize:13, color:accent, bold:true, fontFace:FB, align:'left' });

  // accent rule
  s.addShape(pres.shapes.RECTANGLE, { x:0.55,y:1.45,w:12.25,h:0.025, fill:{color:accent,transparency:40}, line:{type:'none'} });

  // LEFT (features cards) — RTL means description goes RIGHT, features LEFT
  const fx = 0.55, fy = 1.75, fw = 5.6;
  const fh = (5.0 - (features.length-1)*0.25) / features.length;
  features.forEach((f,i)=>{
    const y = fy + i*(fh+0.25);
    card(s,fx,y,fw,fh,accent,C.navy);
    s.addShape(pres.shapes.RECTANGLE,{x:fx,y,w:0.07,h:fh,fill:{color:accent},line:{type:'none'}});
    s.addText(f.h, { x:fx+0.2,y:y+0.12,w:fw-0.4,h:0.4, fontSize:14, color:accent, bold:true, fontFace:FB, align:'right' });
    s.addText(f.d, { x:fx+0.2,y:y+0.52,w:fw-0.4,h:fh-0.6, fontSize:12, color:C.white, fontFace:FB, align:'right', valign:'top' });
  });

  // RIGHT (description)
  const dx = 6.5, dw = 6.3;
  card(s,dx,1.75,dw,2.55,accent,C.navyMid);
  s.addText('▸ ما هي الأداة؟', { x:dx+0.25,y:1.9,w:dw-0.5,h:0.4, fontSize:16, color:accent, bold:true, fontFace:FB, align:'right' });
  s.addText(desc, { x:dx+0.25,y:2.35,w:dw-0.5,h:1.85, fontSize:13.5, color:C.white, fontFace:FB, align:'right', valign:'top', lineSpacingMultiple:1.15 });

  card(s,dx,4.5,dw,2.25,C.gold,C.navyMid);
  s.addText('▸ كيف تعمل؟', { x:dx+0.25,y:4.62,w:dw-0.5,h:0.4, fontSize:16, color:C.gold, bold:true, fontFace:FB, align:'right' });
  how.forEach((h,i)=>{
    s.addShape(pres.shapes.OVAL,{x:dx+dw-0.55,y:5.12+i*0.42,w:0.22,h:0.22,fill:{color:C.gold},line:{type:'none'}});
    s.addText(String(i+1),{x:dx+dw-0.55,y:5.12+i*0.42,w:0.22,h:0.22,fontSize:10,color:C.bg,bold:true,align:'center',valign:'middle',margin:0,fontFace:FB});
    s.addText(h,{x:dx+0.25,y:5.08+i*0.42,w:dw-0.95,h:0.38,fontSize:12,color:C.white,fontFace:FB,align:'right',valign:'middle'});
  });

  footer(s, idx+2);
  return s;
}

